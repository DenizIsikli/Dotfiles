		local blank = "⠀"
		local x_art_offset = 8
		local y_art_offset = 4

		local function count_blank(line, from_end)
			local n, len = 0, vim.fn.strchars(line)
			while n < len do
				local idx = from_end and (len - 1 - n) or n
				if vim.fn.strcharpart(line, idx, 1) ~= blank then
					break
				end
				n = n + 1
			end
			return n, len
		end

		local function trim_art(lines)
			local lead, trail = math.huge, math.huge
			for _, line in ipairs(lines) do
				local l, len = count_blank(line, false)
				if l < len then
					lead = math.min(lead, l)
					trail = math.min(trail, (count_blank(line, true)))
				end
			end
			local pad = string.rep(blank, math.abs(x_art_offset))
			local out = {}
			for _, line in ipairs(lines) do
				local len = vim.fn.strchars(line)
				local trimmed = vim.fn.strcharpart(line, lead, math.max(len - lead - trail, 0))
				if x_art_offset > 0 then
					trimmed = pad .. trimmed
				elseif x_art_offset < 0 then
					trimmed = trimmed .. pad
				end
				table.insert(out, trimmed)
			end
			return out
		end

		dashboard.section.header.val = trim_art(dashboard.section.header.val)

		local function section_title(text)
			return {
				type = "text",
				val = text,
				opts = { position = "center", hl = "AlphaTitle" },
			}
		end

		local function style(button)
			button.opts.hl = "AlphaButtons"
			button.opts.hl_shortcut = "AlphaShortcut"
			return button
		end

		local function recent_projects()
			local code = vim.fn.expand("~/Code") .. "/"
			local seen, buttons = {}, {}
			for _, file in ipairs(vim.v.oldfiles) do
				if vim.startswith(file, code) then
					local name = file:sub(#code + 1):match("^([^/]+)/")
					local path = code .. (name or "")
					if name and not seen[name] and vim.fn.isdirectory(path) == 1 then
						seen[name] = true
						local key = tostring(#buttons + 1)
						local cmd = ":cd " .. vim.fn.fnameescape(path) .. " | edit .<CR>"
						table.insert(buttons, style(dashboard.button(key, "  " .. name, cmd)))
						if #buttons == 8 then
							break
						end
					end
				end
			end
			if #buttons == 0 then
				return {
					{
						type = "text",
						val = "No recent projects",
						opts = { position = "center", hl = "AlphaMuted" },
					},
				}
			end
			return buttons
		end

